package com.android.server.power;

/** Internal, non-persistent markers for the authenticated duress wipe path. */
public final class DuressReboot {
    public static final String RECOVERY = "recovery-duress";
    public static final String FALLBACK = "duress";

    private DuressReboot() {}

    public static boolean isDuressReboot(String reason) {
        return RECOVERY.equals(reason) || FALLBACK.equals(reason);
    }

    /**
     * Only the unattended wipe command generated by RecoverySystem may hide UI.
     * Reject mixed operations, duplicate reasons, and lookalike reason prefixes.
     */
    public static boolean isDuressWipeCommand(String command) {
        if (command == null) {
            return false;
        }
        int wipes = 0;
        int reasons = 0;
        for (String arg : command.split("\n")) {
            if ("--wipe_data".equals(arg)) {
                wipes++;
            } else if ("--reason=duress".equals(arg)
                    || arg.startsWith("--reason=duress,")) {
                reasons++;
            } else if (!arg.startsWith("--locale=")
                    && !"--shutdown_after".equals(arg)
                    && !"--keep_memtag_mode".equals(arg)) {
                return false;
            }
        }
        return wipes == 1 && reasons == 1;
    }

    /** Reserved reboot markers may only originate inside system_server. */
    public static boolean isTrustedCaller(int uid, int pid, int systemUid, int systemPid) {
        return uid == systemUid && pid == systemPid;
    }
}
